import { Link } from 'react-router-dom';
import { ErrorState, PageHeader, Spinner, StatusBadge, formatDateTime } from '../../components/ui';
import { useAuth } from '../../context/AuthContext';
import { useFetch } from '../../hooks/useFetch';
import { api } from '../../services/api';
import type { ActivityItem, Article, Paged, Stats } from '../../types';

export default function OverviewPage() {
  const { user, isStaff } = useAuth();
  const stats = useFetch(() => api.get<Stats>('/admin/stats'), []);
  const activity = useFetch(() => api.get<{ items: ActivityItem[] }>('/admin/activity/recent'), []);
  const pending = useFetch(() => api.get<Paged<Article>>('/admin/articles?status=pending_approval&limit=5'), []);

  if (stats.loading && !stats.data) return <Spinner />;
  if (stats.error || !stats.data) return <ErrorState message={stats.error || 'Could not load statistics'} onRetry={stats.reload} />;
  const s = stats.data;

  const tiles: { label: string; value: number; to: string }[] = [
    { label: 'Total articles', value: s.total, to: '/admin/articles' },
    { label: 'Published', value: s.published, to: '/admin/articles?status=published' },
    { label: 'Drafts', value: s.draft, to: '/admin/articles?status=draft' },
    { label: 'Scheduled', value: s.scheduled, to: '/admin/articles?status=scheduled' },
    { label: 'Pending approval', value: s.pendingApproval, to: '/admin/articles?status=pending_approval' },
    { label: 'Created manually', value: s.manual, to: '/admin/articles?origin=manual' },
    { label: 'Generated by AI', value: s.aiGenerated, to: '/admin/articles?origin=ai' },
    { label: 'Archived', value: s.archived, to: '/admin/articles?status=archived' },
  ];

  return (
    <div>
      <PageHeader
        title={`Welcome, ${user?.name}`}
        subtitle={isStaff ? 'Everything across the site at a glance.' : 'Your articles at a glance.'}
        actions={
          <Link to="/admin/articles/new" className="btn btn-primary">
            + New article
          </Link>
        }
      />
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        {tiles.map((t) => (
          <Link key={t.label} to={t.to} className="card p-5 transition hover:border-brand-500">
            <p className="text-sm text-stone-500">{t.label}</p>
            <p className="mt-2 font-serif text-3xl font-semibold text-stone-900 dark:text-stone-50">{t.value}</p>
          </Link>
        ))}
      </div>

      <div className="mt-8 grid gap-6 lg:grid-cols-2">
        <section className="card p-5">
          <h2 className="font-sans text-base font-semibold">Pending approvals</h2>
          {pending.loading && !pending.data ? (
            <Spinner />
          ) : pending.error ? (
            <ErrorState message={pending.error} onRetry={pending.reload} />
          ) : pending.data && pending.data.items.length ? (
            <ul className="mt-3 divide-y divide-stone-200 dark:divide-stone-800">
              {pending.data.items.map((a) => (
                <li key={a._id} className="flex items-center justify-between gap-3 py-3">
                  <div className="min-w-0">
                    <Link to={`/admin/articles/${a._id}/edit`} className="block truncate font-medium hover:text-brand-700">
                      {a.title}
                    </Link>
                    <p className="text-xs text-stone-500">
                      {a.author?.name} · updated {formatDateTime(a.updatedAt)}
                    </p>
                  </div>
                  <StatusBadge status={a.status} />
                </li>
              ))}
            </ul>
          ) : (
            <p className="mt-3 text-sm text-stone-500">Nothing is waiting for approval.</p>
          )}
        </section>

        <section className="card p-5">
          <h2 className="font-sans text-base font-semibold">Recent activity</h2>
          {activity.loading && !activity.data ? (
            <Spinner />
          ) : activity.error ? (
            <ErrorState message={activity.error} onRetry={activity.reload} />
          ) : activity.data && activity.data.items.length ? (
            <ul className="mt-3 divide-y divide-stone-200 dark:divide-stone-800">
              {activity.data.items.map((a) => (
                <li key={a._id} className="py-3 text-sm">
                  <p>{a.summary || a.action}</p>
                  <p className="text-xs text-stone-500">
                    {a.actorName} · {formatDateTime(a.createdAt)}
                  </p>
                </li>
              ))}
            </ul>
          ) : (
            <p className="mt-3 text-sm text-stone-500">No activity yet.</p>
          )}
        </section>
      </div>
    </div>
  );
}
