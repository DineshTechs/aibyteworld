import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';
import { z } from 'zod';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const SERVER_ROOT = path.resolve(__dirname, '..', '..');

dotenv.config({ path: path.join(SERVER_ROOT, '.env') });

const schema = z.object({
  NODE_ENV: z.enum(['development', 'test', 'production']).default('development'),
  PORT: z.coerce.number().int().positive().default(5000),
  CLIENT_ORIGIN: z.string().default('http://localhost:5173'),
  LOG_LEVEL: z.string().default('info'),
  MONGODB_URI: z.string().min(1, 'MONGODB_URI is required (see server/.env.example)'),
  DB_NAME: z.string().min(1).default('blogsite'),
  JWT_SECRET: z.string().min(32, 'JWT_SECRET must be at least 32 characters (run "npm run gen:secret")'),
  JWT_EXPIRES_IN: z.string().default('12h'),
  UPLOAD_MAX_MB: z.coerce.number().positive().default(5),
  // Encrypts API keys stored in the database. Generated by "npm run gen:secret".
  SECRETS_KEY: z.string().optional().default(''),
  // Optional: a Gemini key in .env is used when none is saved in the dashboard.
  GEMINI_API_KEY: z.string().optional().default(''),
  OPENAI_API_KEY: z.string().optional().default(''),
  ANTHROPIC_API_KEY: z.string().optional().default(''),
  NOUS_API_KEY: z.string().optional().default(''),
  TAVILY_API_KEY: z.string().optional().default(''),
  GROQ_API_KEY: z.string().optional().default(''),
  CEREBRAS_API_KEY: z.string().optional().default(''),
  MISTRAL_API_KEY: z.string().optional().default(''),
  OPENROUTER_API_KEY: z.string().optional().default(''),
  OLLAMA_BASE_URL: z.string().optional().default(''),
  // Free photo libraries for post images (optional; can also be set in AI Providers).
  UNSPLASH_ACCESS_KEY: z.string().optional().default(''),
  PEXELS_API_KEY: z.string().optional().default(''),
  PIXABAY_API_KEY: z.string().optional().default(''),
  // Optional: where the built website lives (default ../client/dist). When it
  // exists, the API server also serves the website with server-side SEO tags.
  CLIENT_DIST: z.string().optional().default(''),
});

const parsed = schema.safeParse(process.env);
if (!parsed.success) {
  const lines = parsed.error.issues.map((i) => `  - ${i.path.join('.')}: ${i.message}`);
  // eslint-disable-next-line no-console
  console.error(`Invalid environment configuration:\n${lines.join('\n')}`);
  process.exit(1);
}

export const env = {
  ...parsed.data,
  clientOrigins: parsed.data.CLIENT_ORIGIN.split(',').map((s) => s.trim()).filter(Boolean),
  uploadDir: path.join(SERVER_ROOT, 'uploads'),
  isProd: parsed.data.NODE_ENV === 'production',
  isTest: parsed.data.NODE_ENV === 'test',
};
